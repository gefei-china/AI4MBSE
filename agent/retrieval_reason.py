"""检索零命中/低分的**成因分离**（S4 · 2026-10-29）。

## 为什么需要（真库实测，纠正了上一轮的结论）

上一轮核查报告写的是「检索 **21% 零命中**」，暗示这是召回质量问题。
本轮把 59 条零命中逐条看过后，结论要改：

| 构成 | 条数 | 占比 | 性质 |
|---|---|---|---|
| 指令性文本（`请生成…`/`请基于…`/`【澄清补充】…`） | 24 | **40%** | **本就不该走知识库** |
| 业务数据查询（`智源工程列表`/`工程 projectId`/`包结构`） | 9 | **15%** | 应走工具（query_projects 等） |
| 其余 | 26 | 44% | 含语料缺口（飞控系统文档不存在）与测试噪声（`q0`/`q1`） |

⇒ **≥55% 的"零命中"不是检索错了，是"检索被用在了不该用的地方"**。
把这两类混在一起统计，会让"召回质量"这个指标长期看起来很差，
而实际该改的是**调用侧的语义错配**（或在检索入口识别出来），
不是去调向量/BM25 的参数——**方向都会搞错**。

## 本模块做什么 / 不做什么

**只做归因**：把 `no_hit_fallback` 细分成可区分的 reason，让统计口径真实。
**不做拦截**：是否要在检索前就跳过这类查询，是行为变更，需要先有真实分布数据
再决定（先观测、后优化——避免"为了解决 A 制造 B"）。

reason 取值：
- `no_hit_directive`     指令/对话文本（含"请生成/请基于/澄清补充"等祈使开头）
- `no_hit_biz_query`     业务数据查询（工程/项目/分支/版本/包结构…）
- `no_hit_tiny`          过短噪声（<3 字符，如 q0/q1/单个汉字）
- `no_hit_corpus_gap`    其余：看起来是正常知识问题但没命中 ⇒ **这才是召回问题**

⚠️ 判定只基于**形态特征**（前缀/关键词/长度），不调 LLM、不查库 ⇒ 零成本、可解释、可回退。
"""
from __future__ import annotations

import re

#: 祈使/指令性开头（用户在下达任务，不是提问）
_DIRECTIVE_HEAD = re.compile(
    r"^\s*(请|帮我|帮忙|麻烦|给我|生成|基于|继续|再生成|重新生成|补充|按|用|把|将|"
    r"【|\[|#|现在请|接下来请)"
)

#: 指令性动词出现在句首 20 字内（"我的目标是生成…"这种被动语态也算）
#: ⚠️ 2026-10-29 标定补入 `目标是生成` 与 `生成…（视图|模型|代码|图）`：
#:   实测样本「我的目标是生成状态机视图」原被判成 corpus_gap（错），
#:   而它显然是指令 —— 这会让"真实召回失败率"虚高。
#:   反向约束：`生成` 出现在知识型提问里时（"如何生成状态机视图"）已被
#:   `_KB_TERMS` 的「如何」提前保护，不会误判。
_DIRECTIVE_ANY = re.compile(
    r"(请生成|请基于|请按|请继续|请调用|请校验|帮我生成|继续生成|重新生成|"
    r"澄清补充|待澄清|调用\s*[A-Za-z_][A-Za-z0-9_]*\s*校验|"
    r"目标是生成|目标是产出|"
    r"(生成|产出|输出|绘制|画)[^。；\n]{0,12}(视图|模型|代码|图))"
)

#: 业务数据查询特征（问的是平台里的对象，不是文档里的知识）
_BIZ_TERMS = re.compile(
    r"(工程列表|项目列表|工程\s*projectId|projectId|project_id|"
    r"模型树|包结构|包树|分支列表|branch|版本列表|"
    r"工程\s+包\s+模型|当前工程|有哪些工程|有哪些项目|哪些分支)"
)

#: 明确是知识型提问的形态（用来**保护**：带这些词的不要被判成业务查询）
#: ⚠️ 2026-10-29 标定：**去掉裸 `定义`** —— 实测样本里 `块定义图_BDD` 的「定义」
#:   命中了它，把一句指令（【澄清补充】…块定义图_BDD 视图…）误判成知识提问。
#:   建模语境里「定义」是产物名的一部份（Block **Definition** Diagram），
#:   不等于用户在问"定义是什么"。改为只认明确的提问搭配。
_KB_TERMS = re.compile(
    r"(是什么|什么是|什么意思|怎么|如何|为什么|原理|方法论|规范要求|标准要求|"
    r"区别|对比|含义|概念|解释|流程|步骤|做法|最佳实践|"
    r"定义是什么|的定义是|有何区别|有何不同)"
)


def classify_no_hit(query) -> str:
    """把"零命中"细分成成因。返回 reason 字符串（**不为 None**，便于直接落库）。

    判定顺序（先排除最容易误判的）：
        1. 过短噪声 → tiny（这些进统计本身就是污染）
        2. 含知识型提问词 → corpus_gap（**保护性优先**：宁可算作召回问题，也不误判成"不该检索"）
        3. 指令性 → directive
        4. 业务查询 → biz_query
        5. 其余 → corpus_gap
    """
    q = str(query or "").strip()
    if len(q) < 3:
        return "no_hit_tiny"
    # ① 知识型提问优先保护：这类即使带"请"字也确实是知识问题
    if _KB_TERMS.search(q):
        return "no_hit_corpus_gap"
    # ② 指令性（开头祈使 或 句中出现明确的指令动词组合）
    if _DIRECTIVE_HEAD.match(q) or _DIRECTIVE_ANY.search(q):
        return "no_hit_directive"
    # ③ 业务数据查询
    if _BIZ_TERMS.search(q):
        return "no_hit_biz_query"
    return "no_hit_corpus_gap"


def refine_reason(query, route: str, reason: str) -> str:
    """仅在「零命中」这一种 reason 上细分；其它 reason 原样返回（零侵入）。

    为什么只细分 `no_hit_fallback`：
        它是唯一"路由与召回都无法解释"的状态。`graph_no_hit`（图没命中但向量命中）
        与 `graph_hit_insufficient_confidence` 都已自带成因，再细分是无意义的叠加。
    """
    try:
        if str(reason or "") == "no_hit_fallback" and str(route or "") == "vector":
            return classify_no_hit(query)
    except Exception:
        pass
    return reason


def is_real_recall_problem(reason) -> bool:
    """该 reason 是否代表**真的召回问题**（供看板算真实召回失败率）。

    只有 `no_hit_corpus_gap` 算：其余三类都说明"这次检索本不该发生或样本无意义"。
    ⚠️ 这个划分必须显式给出——否则看板负责人会继续把 55% 的错配算进召回失败率。
    """
    return str(reason or "") == "no_hit_corpus_gap"
